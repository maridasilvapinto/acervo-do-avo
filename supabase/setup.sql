-- Quem pode usar a app (emails autorizados)
create table if not exists public.acervo_membros (
  email         text primary key check (email = lower(email)),
  adicionado_em timestamptz not null default now()
);

-- Os livros: um registo por exemplar físico
create table if not exists public.acervo_livros (
  id              uuid primary key default gen_random_uuid(),
  numero          integer generated by default as identity,
  titulo          text not null,
  autor           text,
  ano             integer,
  edicao          text,
  idioma          text,
  editora         text,
  local_edicao    text,
  categoria       text,
  isbn            text,
  estado          text,
  encadernacao    text,
  primeira_edicao boolean not null default false,
  autografado     boolean not null default false,
  ilustrado       boolean not null default false,
  localizacao     text,
  preco_min       numeric(10,2),
  preco_max       numeric(10,2),
  preco_pedido    numeric(10,2),
  status          text not null default 'catalogado'
                  check (status in ('catalogado','venda','reservado','vendido','guardar')),
  preco_venda     numeric(10,2),
  data_venda      date,
  comprador       text,
  notas           text,
  fotos           text[] not null default '{}',
  criado_por      text default lower(auth.jwt() ->> 'email'),
  criado_em       timestamptz not null default now(),
  atualizado_em   timestamptz not null default now()
);

create index if not exists acervo_livros_numero_idx on public.acervo_livros (numero);

-- Atualiza a data de alteração automaticamente
create or replace function public.acervo_tocar() returns trigger
language plpgsql set search_path = public as $$
begin
  new.atualizado_em := now();
  return new;
end $$;

drop trigger if exists acervo_livros_tocar on public.acervo_livros;
create trigger acervo_livros_tocar before update on public.acervo_livros
  for each row execute function public.acervo_tocar();

-- A pessoa com sessão iniciada está autorizada?
create or replace function public.acervo_e_membro() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.acervo_membros
    where email = lower(auth.jwt() ->> 'email')
  );
$$;

-- Chamada ao entrar. A primeira pessoa a entrar fica autorizada;
-- as seguintes têm de ser adicionadas por quem já está.
create or replace function public.acervo_entrar() returns boolean
language plpgsql security definer set search_path = public as $$
declare
  e text := lower(auth.jwt() ->> 'email');
begin
  if e is null then
    return false;
  end if;
  perform pg_advisory_xact_lock(424242);
  if not exists (select 1 from public.acervo_membros) then
    insert into public.acervo_membros (email) values (e);
  end if;
  return exists (select 1 from public.acervo_membros where email = e);
end $$;

-- Depois de repor um backup, acerta o contador dos números de registo
create or replace function public.acervo_acertar_numeros() returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.acervo_e_membro() then
    raise exception 'sem acesso';
  end if;
  perform setval(
    pg_get_serial_sequence('public.acervo_livros', 'numero'),
    coalesce((select max(numero) from public.acervo_livros), 0) + 1,
    false
  );
end $$;

revoke all on function public.acervo_e_membro()        from public, anon;
revoke all on function public.acervo_entrar()          from public, anon;
revoke all on function public.acervo_acertar_numeros() from public, anon;
grant execute on function public.acervo_e_membro()        to authenticated;
grant execute on function public.acervo_entrar()          to authenticated;
grant execute on function public.acervo_acertar_numeros() to authenticated;

-- Permissões: só pessoas autorizadas veem ou alteram alguma coisa
alter table public.acervo_membros enable row level security;
alter table public.acervo_livros  enable row level security;

revoke all on public.acervo_membros, public.acervo_livros from anon;
grant select, insert, delete         on public.acervo_membros to authenticated;
grant select, insert, update, delete on public.acervo_livros  to authenticated;
grant usage, select on sequence public.acervo_livros_numero_seq to authenticated;

drop policy if exists "membros veem membros"       on public.acervo_membros;
drop policy if exists "membros adicionam membros"  on public.acervo_membros;
drop policy if exists "membros removem membros"    on public.acervo_membros;
drop policy if exists "membros gerem livros"       on public.acervo_livros;

create policy "membros veem membros" on public.acervo_membros
  for select to authenticated using (public.acervo_e_membro());
create policy "membros adicionam membros" on public.acervo_membros
  for insert to authenticated with check (public.acervo_e_membro());
create policy "membros removem membros" on public.acervo_membros
  for delete to authenticated
  using (public.acervo_e_membro() and email <> lower(auth.jwt() ->> 'email'));
create policy "membros gerem livros" on public.acervo_livros
  for all to authenticated
  using (public.acervo_e_membro()) with check (public.acervo_e_membro());

-- Atualizações em tempo real (o que uma pessoa grava aparece logo às outras)
do $$
begin
  alter publication supabase_realtime add table public.acervo_livros;
exception when duplicate_object then null;
end $$;

-- Fotografias: pasta privada, só para pessoas autorizadas
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('acervo-fotos', 'acervo-fotos', false, 10485760, array['image/jpeg','image/png','image/webp'])
on conflict (id) do nothing;

drop policy if exists "acervo fotos ver"    on storage.objects;
drop policy if exists "acervo fotos enviar" on storage.objects;
drop policy if exists "acervo fotos apagar" on storage.objects;

create policy "acervo fotos ver" on storage.objects
  for select to authenticated
  using (bucket_id = 'acervo-fotos' and public.acervo_e_membro());
create policy "acervo fotos enviar" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'acervo-fotos' and public.acervo_e_membro());
create policy "acervo fotos apagar" on storage.objects
  for delete to authenticated
  using (bucket_id = 'acervo-fotos' and public.acervo_e_membro());

select 'Acervo do Avô: base de dados pronta' as resultado;
